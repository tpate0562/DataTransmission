// Validates questions/*.json and bundles the decks into plain <script> files, so index.html
// works when opened straight from disk (file://), where fetch() and XHR are blocked.
//
//   node tools/build.js
//
// Writes decks/pstat100-midterm.js and preset-decks/presets.js.

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");
const { sections, chapters } = require("./sections.js");

const ROOT = path.join(__dirname, "..");
const HEADER = "// Generated by tools/build.js. Do not edit by hand.\n";

function write(relPath, body) {
    let file = path.join(ROOT, relPath);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, HEADER + body + "\n");
    console.log("wrote " + relPath + " (" + Math.round(fs.statSync(file).size / 1024) + " KB)");
}

function buildQuestionDeck() {
    execFileSync(process.execPath, [path.join(__dirname, "validate.js")], { stdio: "inherit" });

    let dir = path.join(ROOT, "questions");
    let questions = [];
    for (let file of fs.readdirSync(dir).filter(f => f.endsWith(".json")).sort()) {
        questions = questions.concat(JSON.parse(fs.readFileSync(path.join(dir, file), "utf8")));
    }

    let order = Object.keys(sections);
    questions.sort((a, b) => order.indexOf(a.section) - order.indexOf(b.section));

    let deck = {
        id: "pstat100-midterm",
        title: "PSTAT 100 Midterm Practice Test",
        sections: sections,
        chapters: chapters,
        questions: questions
    };
    write("decks/pstat100-midterm.js",
        "window.DASHCARDS_DECKS = window.DASHCARDS_DECKS || {};\n"
        + "window.DASHCARDS_DECKS[\"pstat100-midterm\"] = " + JSON.stringify(deck, null, 1) + ";");
}

function buildPresets() {
    let dir = path.join(ROOT, "preset-decks");
    let presets = {};
    for (let file of fs.readdirSync(dir).filter(f => f.endsWith(".txt")).sort()) {
        presets[file] = fs.readFileSync(path.join(dir, file), "utf8");
    }
    write("preset-decks/presets.js", "window.DASHCARDS_PRESETS = " + JSON.stringify(presets, null, 1) + ";");
}

buildQuestionDeck();
buildPresets();
